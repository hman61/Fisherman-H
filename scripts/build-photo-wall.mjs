// Scans public/images for jpg/jpeg files (excluding every-piece-refined) and
// writes data/photo-wall.ts with the results grouped by portrait/landscape.
import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { extname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const rootDir = fileURLToPath(new URL('..', import.meta.url))
const imagesDir = join(rootDir, 'public', 'images')
const outFile = join(rootDir, 'data', 'photo-wall.ts')
const excludedDirName = 'every-piece-refined'
const excludedFileNames = new Set(['river-at-sunset.jpg', 'social-preview.jpg', 'video-poster.jpg'])

function walk(dir, files = []) {
  for (const entry of readdirSync(dir)) {
    if (entry === excludedDirName) continue
    const fullPath = join(dir, entry)
    const stats = statSync(fullPath)
    if (stats.isDirectory()) {
      walk(fullPath, files)
    } else if (/\.(jpe?g)$/i.test(extname(entry)) && !excludedFileNames.has(entry)) {
      files.push(fullPath)
    }
  }
  return files
}

function getDimensions(filePath) {
  const output = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', filePath], {
    encoding: 'utf8'
  })
  const width = Number(output.match(/pixelWidth:\s*(\d+)/)?.[1])
  const height = Number(output.match(/pixelHeight:\s*(\d+)/)?.[1])
  return { width, height }
}

function toAlt(filePath) {
  const base = filePath.split('/').pop().replace(/\.[^.]+$/, '')
  return base.replace(/^\d+-/, '').replace(/[-_]+/g, ' ').trim()
}

const files = walk(imagesDir).sort()

const portrait = []
const landscape = []

for (const filePath of files) {
  const { width, height } = getDimensions(filePath)
  if (!width || !height) continue
  const src = `/${relative(join(rootDir, 'public'), filePath).split('\\').join('/')}`
  const entry = { src, alt: toAlt(filePath), width, height }
  if (height > width) {
    portrait.push(entry)
  } else {
    landscape.push(entry)
  }
}

const banner = '// Auto-generated by scripts/build-photo-wall.mjs — do not edit by hand.\n'
const content =
  `${banner}` +
  `export type PhotoWallImage = {\n  src: string\n  alt: string\n  width: number\n  height: number\n}\n\n` +
  `export const portraitPhotos: PhotoWallImage[] = ${JSON.stringify(portrait, null, 2)}\n\n` +
  `export const landscapePhotos: PhotoWallImage[] = ${JSON.stringify(landscape, null, 2)}\n`

mkdirSync(join(rootDir, 'data'), { recursive: true })
writeFileSync(outFile, content)

console.log(`Wrote ${portrait.length} portrait and ${landscape.length} landscape photos to ${relative(rootDir, outFile)}`)
